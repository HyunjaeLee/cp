template <typename T> T ceil_div(T a, T b) { return a / b + static_cast<T>((a ^ b) > 0 && a % b != 0); }
template <typename T> T floor_div(T a, T b) { return a / b - static_cast<T>((a ^ b) < 0 && a % b != 0); }
template <typename T> void read(vector<T> &a) { for (auto &x : a) cin >> x; }
template <typename T> void show(const vector<T> &a, string_view sep = " ", string_view end = "\n") {
    for (auto i = 0; i < int(a.size()); ++i) {
        if (i) cout << sep;
        cout << a[i];
    }
    cout << end;
}
// clang-format on

void solve() {
    int N, D;
    string S;
    cin >> N >> D >> S;
    vector<int> A(N, 1);
    for (auto i = 0; i < N; ++i) {
        if (S[i] == 'G') {
            for (auto j = max(0, i - D); j <= min(N - 1, i + D); ++j) {
                A[j] = 0;
            }
        }
    }
    auto ans = accumulate(begin(A), end(A), 0);
    cout << ans << "\n";
}

int main() {
    cin.tie(0)->sync_with_stdio(0);
    int t = 1;
#ifdef TC
    cin >> t;
#endif
    for (auto i = 0; i < t; ++i) {
        solve();
    }
}
