#ifndef LINEAR_SIEVE_HPP
#define LINEAR_SIEVE_HPP

#include <cassert>
#include <map>
#include <vector>

struct linear_sieve {
    explicit linear_sieve(int n) : lpf(n + 1) {
        for (auto i = 2; i <= n; ++i) {
            if (lpf[i] == 0) {
                lpf[i] = i;
                primes.push_back(i);
            }
            for (auto p : primes) {
                if (lpf[i] < p || n < 1LL * i * p) {
                    break;
                }
                lpf[i * p] = p;
            }
        }
    }
    std::map<int, int> factorize(int x) const { // O(log x)
        assert(1 <= x && x < int(lpf.size()));
        std::map<int, int> f;
        while (1 < x) {
            ++f[lpf[x]];
            x /= lpf[x];
        }
        return f;
    }
    bool is_prime(int x) const { // O(1)
        assert(1 <= x && x < int(lpf.size()));
        return lpf[x] == x;
    }
    std::vector<int> lpf;
    std::vector<int> primes;
};

#endif // LINEAR_SIEVE_HPP

#define TC
void solve() {
    int N;
    cin >> N;
    linear_sieve sieve(N);
    auto p = 0;
    for (auto i = max(2, N / 3 - 1);; ++i) {
        if (sieve.is_prime(i)) {
            p = i;
            break;
        }
    }
    vector<int> A{p};
    for (auto i = 1; i < N / 3 - 1; ++i) {
        A.push_back(p + i);
        A.push_back(p - i);
    }
    vector<bool> used(N + 1);
    for (auto i = 0; i < int(A.size()); ++i) {
        used[A[i]] = true;
    }
    for (auto i = 1; i <= N; ++i) {
        if (!used[i]) {
            A.push_back(i);
        }
    }
    show(A);
}

int main() {
    cin.tie(0)->sync_with_stdio(0);
    int t = 1;
#ifdef TC
    cin >> t;
#endif
    for (auto i = 0; i < t; ++i) {
        solve();
    }
}
